from pathlib import Path
import base64, json
root = Path(__file__).resolve().parents[1]
originals = ['character', 'skin1', 'skin2', 'hair', 'shirt', 'pants', 'shoes', 'eyes']
files = [root / 'assets' / (name + '.png') for name in originals]
files += sorted((root / 'assets/placeholders').rglob('*.svg'))
assets = {p.relative_to(root).as_posix(): 'data:' + ('image/svg+xml' if p.suffix == '.svg' else 'image/png') + ';base64,' + base64.b64encode(p.read_bytes()).decode() for p in files}
(root / 'asset-data.js').write_text('// Generated by tools/build-assets.py; do not edit by hand.\nwindow.DRESSCODE_ASSETS = ' + json.dumps(assets, separators=(',', ':')) + ';\n')
print(f'Embedded {len(assets)} character and clothing images.')
